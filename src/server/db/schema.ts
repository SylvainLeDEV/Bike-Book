/**
 * Database schema (Drizzle ORM, SQLite).
 *
 * Conventions (docs/03-data-model.md): instants stored as UTC epoch milliseconds, enums as text
 * with CHECK constraints, defaults computed in the application rather than in SQLite-only SQL.
 */
import { sql, type AnyColumn } from "drizzle-orm";
import { check, index, integer, primaryKey, sqliteTable, text } from "drizzle-orm/sqlite-core";

const now = () => new Date();

const createdAt = () => integer("created_at", { mode: "timestamp_ms" }).notNull().$defaultFn(now);
const updatedAt = () =>
  integer("updated_at", { mode: "timestamp_ms" }).notNull().$defaultFn(now).$onUpdate(now);

/** CHECK constraint restricting a text column to a fixed list of values. */
function enumCheck(name: string, column: AnyColumn, values: readonly string[]) {
  const list = values.map((value) => `'${value.replaceAll("'", "''")}'`).join(", ");
  return check(name, sql`${column} in (${sql.raw(list)})`);
}

// --- Auth tables -------------------------------------------------------------------------------
// Shape required by Better Auth (generated with `auth generate`, then adapted to the naming
// conventions above). Ids are random strings generated by Better Auth (D-26).

export const users = sqliteTable("users", {
  id: text("id").primaryKey(),
  name: text("name").notNull(),
  email: text("email").notNull().unique(),
  emailVerified: integer("email_verified", { mode: "boolean" }).notNull().default(false),
  image: text("image"),
  createdAt: createdAt(),
  updatedAt: updatedAt(),
});

export const sessions = sqliteTable(
  "sessions",
  {
    id: text("id").primaryKey(),
    expiresAt: integer("expires_at", { mode: "timestamp_ms" }).notNull(),
    token: text("token").notNull().unique(),
    ipAddress: text("ip_address"),
    userAgent: text("user_agent"),
    userId: text("user_id")
      .notNull()
      .references(() => users.id, { onDelete: "cascade" }),
    createdAt: createdAt(),
    updatedAt: updatedAt(),
  },
  (table) => [index("sessions_user_id_idx").on(table.userId)],
);

export const accounts = sqliteTable(
  "accounts",
  {
    id: text("id").primaryKey(),
    accountId: text("account_id").notNull(),
    providerId: text("provider_id").notNull(),
    userId: text("user_id")
      .notNull()
      .references(() => users.id, { onDelete: "cascade" }),
    accessToken: text("access_token"),
    refreshToken: text("refresh_token"),
    idToken: text("id_token"),
    accessTokenExpiresAt: integer("access_token_expires_at", { mode: "timestamp_ms" }),
    refreshTokenExpiresAt: integer("refresh_token_expires_at", { mode: "timestamp_ms" }),
    scope: text("scope"),
    password: text("password"),
    createdAt: createdAt(),
    updatedAt: updatedAt(),
  },
  (table) => [index("accounts_user_id_idx").on(table.userId)],
);

export const verifications = sqliteTable(
  "verifications",
  {
    id: text("id").primaryKey(),
    identifier: text("identifier").notNull(),
    value: text("value").notNull(),
    expiresAt: integer("expires_at", { mode: "timestamp_ms" }).notNull(),
    createdAt: createdAt(),
    updatedAt: updatedAt(),
  },
  (table) => [index("verifications_identifier_idx").on(table.identifier)],
);

// --- Workspaces (D-25) -------------------------------------------------------------------------

export const workspaces = sqliteTable("workspaces", {
  id: integer("id").primaryKey({ autoIncrement: true }),
  name: text("name").notNull(),
  createdAt: createdAt(),
});

/** `owner` only for now; `member`, `mechanic`… come with multi-user features (D-25). */
export const MEMBERSHIP_ROLES = ["owner"] as const;
export type MembershipRole = (typeof MEMBERSHIP_ROLES)[number];

export const memberships = sqliteTable(
  "memberships",
  {
    userId: text("user_id")
      .notNull()
      .references(() => users.id, { onDelete: "cascade" }),
    workspaceId: integer("workspace_id")
      .notNull()
      .references(() => workspaces.id, { onDelete: "cascade" }),
    role: text("role", { enum: MEMBERSHIP_ROLES }).notNull(),
    createdAt: createdAt(),
  },
  (table) => [
    primaryKey({ columns: [table.userId, table.workspaceId] }),
    index("memberships_workspace_id_idx").on(table.workspaceId),
    enumCheck("memberships_role_check", table.role, MEMBERSHIP_ROLES),
  ],
);

/** Tables handed to the Better Auth Drizzle adapter (keys follow its plural model names). */
export const authSchema = { users, sessions, accounts, verifications };
